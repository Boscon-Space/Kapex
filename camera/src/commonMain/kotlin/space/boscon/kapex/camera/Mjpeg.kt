    /** The standard DHT segment (marker, length, four tables): 420 bytes. */
    val STANDARD_DHT: ByteArray = run {
        val tables = listOf(0x00 to (DC_LUM_BITS to DC_VALS), 0x10 to (AC_LUM_BITS to AC_LUM_VALS),
            0x01 to (DC_CHR_BITS to DC_VALS), 0x11 to (AC_CHR_BITS to AC_CHR_VALS))
        val body = ArrayList<Int>()
        for ((classId, t) in tables) { body.add(classId); body.addAll(t.first.toList()); body.addAll(t.second.toList()) }
        val len = body.size + 2
        val out = ByteArray(len + 2)
        out[0] = 0xFF.toByte(); out[1] = DHT.toByte(); out[2] = (len shr 8).toByte(); out[3] = (len and 0xFF).toByte()
        body.forEachIndexed { i, v -> out[4 + i] = v.toByte() }
        out
    }

    private fun u8(f: ByteArray, i: Int) = f[i].toInt() and 0xFF

    /**
     * Walk the marker segments from the SOI. Returns (offset of SOF0 or of SOS
     * if no SOF0, whether a DHT was seen), or null if the data is not a JPEG.
     */
    private fun scan(f: ByteArray): Pair<Int, Boolean>? {
        if (f.size < 4 || u8(f, 0) != 0xFF || u8(f, 1) != 0xD8) return null
        var i = 2; var sawDht = false; var sof = -1
        while (i + 3 < f.size) {
            if (u8(f, i) != 0xFF) return null
            val m = u8(f, i + 1)
            if (m == 0xFF) { i++; continue }                    // fill byte
            if (m == 0x01 || m in 0xD0..0xD8) { i += 2; continue } // standalone markers
            if (m == SOS || m == EOI) return (if (sof >= 0) sof else i) to sawDht
            if (m == DHT) sawDht = true
            if (m == SOF0 && sof < 0) sof = i
            val len = (u8(f, i + 2) shl 8) or u8(f, i + 3)
            if (len < 2) return null
            i += 2 + len
        }
        return null
    }

    fun isJpeg(f: ByteArray) = scan(f) != null
    fun hasHuffmanTables(f: ByteArray) = scan(f)?.second ?: false

    /** [frame] with the standard DHT inserted before the frame header; unchanged if it already carries a DHT or is not a JPEG. */
    fun withHuffmanTables(frame: ByteArray): ByteArray {
        val (at, has) = scan(frame) ?: return frame
        if (has) return frame
        val out = ByteArray(frame.size + STANDARD_DHT.size)
        frame.copyInto(out, 0, 0, at)
        STANDARD_DHT.copyInto(out, at)
        frame.copyInto(out, at + STANDARD_DHT.size, at, frame.size)
        return out
    }
}

package space.boscon.kapex.camera

/**
 * MJPEG frames from UVC cameras (the C270 among them) omit the Huffman
 * tables: the "Motion-JPEG" convention is that decoders supply the standard
 * ones from JPEG Annex K. ffmpeg does; ImageIO, QuickTime and most browsers
 * do not. [withHuffmanTables] inserts the standard DHT segment before the
 * frame header so the stored file plays anywhere. 420 bytes per frame.
